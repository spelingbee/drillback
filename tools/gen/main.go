// Command gen writes the two files in this repository that are derived from
// something else, so that they cannot drift from it:
//
//	go run ./tools/gen recipe-spec     > docs/recipe-spec.md
//	go run ./tools/gen recipes-index   > recipes/README.md
//
// CI runs both and fails on a diff. Editing either output by hand is a mistake the
// next `make docs` will silently undo.
package main

import (
	"encoding/json"
	"fmt"
	"io"
	"os"
	"sort"
	"strings"

	restored "github.com/spelingbee/restored"
	"github.com/spelingbee/restored/internal/recipe"
)

func main() {
	if len(os.Args) != 2 {
		fmt.Fprintln(os.Stderr, "usage: gen recipe-spec|recipes-index")
		os.Exit(2)
	}
	var err error
	switch os.Args[1] {
	case "recipe-spec":
		err = writeRecipeSpec(os.Stdout)
	case "recipes-index":
		err = writeRecipesIndex(os.Stdout)
	case "readme-table":
		err = spliceReadmeTable("README.md")
	default:
		fmt.Fprintf(os.Stderr, "gen: unknown target %q\n", os.Args[1])
		os.Exit(2)
	}
	if err != nil {
		fmt.Fprintf(os.Stderr, "gen: %v\n", err)
		os.Exit(1)
	}
}

const generated = "<!-- Generated by `make docs`. Do not edit: run the target instead. -->"

// ---- recipe-spec -----------------------------------------------------------

// schema is the subset of JSON Schema this repository's recipe schema uses.
type schema struct {
	Type                 any                 `json:"type"`
	Ref                  string              `json:"$ref"`
	Const                any                 `json:"const"`
	Enum                 []any               `json:"enum"`
	Pattern              string              `json:"pattern"`
	Format               string              `json:"format"`
	MinLength            *int                `json:"minLength"`
	MaxLength            *int                `json:"maxLength"`
	Minimum              *float64            `json:"minimum"`
	Maximum              *float64            `json:"maximum"`
	MinItems             *int                `json:"minItems"`
	MaxItems             *int                `json:"maxItems"`
	MinProperties        *int                `json:"minProperties"`
	UniqueItems          bool                `json:"uniqueItems"`
	Default              any                 `json:"default"`
	Required             []string            `json:"required"`
	Properties           map[string]*schema  `json:"properties"`
	PropertyNames        *schema             `json:"propertyNames"`
	AdditionalProperties json.RawMessage     `json:"additionalProperties"`
	Items                *schema             `json:"items"`
	AllOf                []*conditional      `json:"allOf"`
	DependentRequired    map[string][]string `json:"dependentRequired"`
	Defs                 map[string]*schema  `json:"$defs"`
	Title                string              `json:"title"`
}

type conditional struct {
	If   *schema `json:"if"`
	Then *schema `json:"then"`
}

// additional returns additionalProperties as a schema, when it is one rather than a
// bare false. It is how this schema says "a map whose values all look like this".
func (s *schema) additional() *schema {
	if len(s.AdditionalProperties) == 0 {
		return nil
	}
	var b bool
	if err := json.Unmarshal(s.AdditionalProperties, &b); err == nil {
		return nil
	}
	var sub schema
	if err := json.Unmarshal(s.AdditionalProperties, &sub); err != nil {
		return nil
	}
	return &sub
}

func writeRecipeSpec(w io.Writer) error {
	raw, err := restored.Schemas.ReadFile("schema/recipe.schema.json")
	if err != nil {
		return err
	}
	var root schema
	if err := json.Unmarshal(raw, &root); err != nil {
		return fmt.Errorf("parsing recipe.schema.json: %w", err)
	}

	b := &strings.Builder{}
	fmt.Fprintf(b, "# Recipe reference\n\n%s\n\n", generated)
	b.WriteString(specPreamble)

	section(b, "The recipe document", "", &root, root.Defs)
	if md := root.Properties["metadata"]; md != nil {
		section(b, "metadata", "The recipe's identity. It is prose, and it is never templated.", md, root.Defs)
	}
	if in := root.Properties["inputs"]; in != nil {
		if v := in.additional(); v != nil {
			section(b, "inputs.&lt;name&gt;",
				"One logical part of a backup. Input names match `"+patternOf(in.PropertyNames)+"`.", v, root.Defs)
		}
	}
	names := []struct{ def, title, intro string }{
		{"probe", "ready[]", "A retried question that says the application has come up at all."},
		{"check", "checks[]", "One assertion about the restored application. Checks run once, in order, and every check runs even after an earlier one has failed."},
		{"step", "test.seed[] and test.export[]", "One action the round-trip harness performs. Steps are not retried: a step either works or the stage fails."},
	}
	for _, n := range names {
		if d := root.Defs[n.def]; d != nil {
			section(b, n.title, n.intro, d, root.Defs)
		}
	}
	if c := root.Defs["check"]; c != nil {
		if e := c.Properties["expect"]; e != nil {
			section(b, "checks[].expect", expectIntro, e, root.Defs)
		}
	}
	writeScalarDefs(b, root.Defs)
	_, err = io.WriteString(w, b.String())
	return err
}

const specPreamble = "A recipe is a directory holding `recipe.yaml`, `compose.yaml`, and optionally a\n" +
	"`test/` directory of assets. This page is the field reference, generated from\n" +
	"[`schema/recipe.schema.json`](../schema/recipe.schema.json) so that it cannot\n" +
	"disagree with what the validator enforces.\n\n" +
	"For how to write one, start with\n" +
	"[CONTRIBUTING.md](../CONTRIBUTING.md#add-a-recipe-in-10-minutes) and\n" +
	"[`recipes/TEMPLATE`](../recipes/TEMPLATE). For why the format is shaped this way,\n" +
	"see [SPEC.md](../SPEC.md) section 3.\n\n" +
	"Two things the tables cannot tell you:\n\n" +
	"- **The schema validates the file as written, with `{{ ... }}` templates\n" +
	"  unexpanded.** That is what lets an editor and the independent validator job use\n" +
	"  it. Values are rendered against a restricted context - `.vars`, `.inputs` and\n" +
	"  `.runID`, and nothing else - after validation.\n" +
	"- **`compose.yaml` has its own schema**,\n" +
	"  [`schema/compose-safety.schema.json`](../schema/compose-safety.schema.json),\n" +
	"  which encodes the isolation rules. Those are hard failures, never warnings.\n\n"

const expectIntro = "The closed vocabulary a check may assert with. A recipe is data, not a program:\n" +
	"there is no expression language here on purpose, and the list is kept short enough\n" +
	"that a reviewer can hold it in their head.\n\n" +
	"Every key present is evaluated, so a failing check reports every way it missed\n" +
	"rather than only the first. One trap worth naming: **`not_empty` counts directory\n" +
	"entries**, so it is only ever met by a directory. For a file, use `size_min: 1`.\n"

func section(b *strings.Builder, title, intro string, s *schema, defs map[string]*schema) {
	fmt.Fprintf(b, "## %s\n\n", title)
	if intro != "" {
		fmt.Fprintf(b, "%s\n\n", intro)
	}
	if len(s.Properties) == 0 {
		fmt.Fprintf(b, "_(no fields)_\n\n")
		return
	}
	required := set(s.Required)
	b.WriteString("| field | type | required | constraints |\n|---|---|---|---|\n")
	for _, name := range sortedKeys(s.Properties) {
		p := s.Properties[name]
		req := ""
		if required[name] {
			req = "yes"
		}
		fmt.Fprintf(b, "| `%s` | %s | %s | %s |\n", name, typeOf(p, defs), req, constraintsOf(p, defs))
	}
	b.WriteString("\n")
	writeConditionals(b, s, defs)
	writeDependent(b, s)
}

// writeConditionals renders the if/then blocks, which is where this schema says which
// fields a `kind` actually uses.
func writeConditionals(b *strings.Builder, s *schema, defs map[string]*schema) {
	for _, c := range s.AllOf {
		if c.If == nil || c.Then == nil {
			continue
		}
		kind := ""
		for _, name := range sortedKeys(c.If.Properties) {
			if v := c.If.Properties[name].Const; v != nil {
				kind = fmt.Sprint(v)
			}
		}
		if kind == "" {
			continue
		}
		fmt.Fprintf(b, "### kind: `%s`\n\n", kind)
		if len(c.Then.Required) > 0 {
			fmt.Fprintf(b, "Also required: %s.\n\n", codeList(c.Then.Required))
		}
		if len(c.Then.Properties) == 0 {
			continue
		}
		required := set(c.Then.Required)
		b.WriteString("| field | type | required | constraints |\n|---|---|---|---|\n")
		for _, name := range sortedKeys(c.Then.Properties) {
			p := c.Then.Properties[name]
			req := ""
			if required[name] {
				req = "yes"
			}
			fmt.Fprintf(b, "| `%s` | %s | %s | %s |\n", name, typeOf(p, defs), req, constraintsOf(p, defs))
		}
		b.WriteString("\n")
	}
}

func writeDependent(b *strings.Builder, s *schema) {
	if len(s.DependentRequired) == 0 {
		return
	}
	b.WriteString("Keys that need another key present:\n\n")
	for _, k := range sortedKeys(s.DependentRequired) {
		fmt.Fprintf(b, "- `%s` needs %s\n", k, codeList(s.DependentRequired[k]))
	}
	b.WriteString("\n")
}

// writeScalarDefs renders the named scalar types the tables refer to.
func writeScalarDefs(b *strings.Builder, defs map[string]*schema) {
	var scalars []string
	for _, name := range sortedKeys(defs) {
		if len(defs[name].Properties) == 0 {
			scalars = append(scalars, name)
		}
	}
	if len(scalars) == 0 {
		return
	}
	b.WriteString("## Named types\n\n| type | definition |\n|---|---|\n")
	for _, name := range scalars {
		fmt.Fprintf(b, "| `%s` | %s |\n", name, constraintsOr(defs[name], "any "+typeName(defs[name].Type)))
	}
	b.WriteString("\n")
}

func typeOf(s *schema, defs map[string]*schema) string {
	if s.Ref != "" {
		return "`" + refName(s.Ref) + "`"
	}
	if s.Const != nil {
		return "const"
	}
	if len(s.Enum) > 0 {
		return "enum"
	}
	if s.Items != nil {
		return "array of " + typeOf(s.Items, defs)
	}
	return typeName(s.Type)
}

func typeName(t any) string {
	switch v := t.(type) {
	case string:
		return v
	case []any:
		parts := make([]string, 0, len(v))
		for _, x := range v {
			parts = append(parts, fmt.Sprint(x))
		}
		return strings.Join(parts, " or ")
	}
	return "object"
}

func constraintsOf(s *schema, _ map[string]*schema) string {
	return constraintsOr(s, "")
}

func constraintsOr(s *schema, fallback string) string {
	var parts []string
	if s.Const != nil {
		parts = append(parts, fmt.Sprintf("must be `%v`", s.Const))
	}
	if len(s.Enum) > 0 {
		vals := make([]string, 0, len(s.Enum))
		for _, e := range s.Enum {
			vals = append(vals, fmt.Sprintf("`%v`", e))
		}
		parts = append(parts, "one of "+strings.Join(vals, ", "))
	}
	if s.Pattern != "" {
		parts = append(parts, "matches `"+s.Pattern+"`")
	}
	if s.Format != "" {
		parts = append(parts, "format `"+s.Format+"`")
	}
	if s.MinLength != nil {
		parts = append(parts, fmt.Sprintf("at least %d characters", *s.MinLength))
	}
	if s.MaxLength != nil {
		parts = append(parts, fmt.Sprintf("at most %d characters", *s.MaxLength))
	}
	if s.Minimum != nil {
		parts = append(parts, fmt.Sprintf("minimum %g", *s.Minimum))
	}
	if s.Maximum != nil {
		parts = append(parts, fmt.Sprintf("maximum %g", *s.Maximum))
	}
	if s.MinItems != nil {
		parts = append(parts, fmt.Sprintf("at least %d items", *s.MinItems))
	}
	if s.MaxItems != nil {
		parts = append(parts, fmt.Sprintf("at most %d items", *s.MaxItems))
	}
	if s.MinProperties != nil {
		parts = append(parts, fmt.Sprintf("at least %d keys", *s.MinProperties))
	}
	if s.UniqueItems {
		parts = append(parts, "unique items")
	}
	if s.Default != nil {
		parts = append(parts, fmt.Sprintf("default `%v`", s.Default))
	}
	if s.PropertyNames != nil && s.PropertyNames.Pattern != "" {
		parts = append(parts, "keys match `"+s.PropertyNames.Pattern+"`")
	}
	if len(parts) == 0 {
		return fallback
	}
	return strings.Join(parts, "; ")
}

func patternOf(s *schema) string {
	if s == nil {
		return ""
	}
	return s.Pattern
}

func refName(ref string) string { return strings.TrimPrefix(ref, "#/$defs/") }

// ---- recipes-index ---------------------------------------------------------

func writeRecipesIndex(w io.Writer) error {
	b := &strings.Builder{}
	fmt.Fprintf(b, "# Bundled recipes\n\n%s\n\n", strings.Replace(generated, "make docs", "make recipes-index", 1))
	b.WriteString(indexPreamble)

	names := recipe.BundledNames()
	b.WriteString("| recipe | application | state it restores | checks | upstream |\n|---|---|---|---|---|\n")
	for _, name := range names {
		r, err := recipe.LoadBundled(name)
		if err != nil {
			return err
		}
		upstream := "-"
		if r.Metadata.Upstream != "" {
			upstream = "[source](" + r.Metadata.Upstream + ")"
		}
		fmt.Fprintf(b, "| [`%s`](%s/) | %s | %s | %d | %s |\n",
			name, name, r.Metadata.Title, inputSummary(r), len(r.Checks), upstream)
	}
	fmt.Fprintf(b, "\n%d recipes.\n\n", len(names))
	b.WriteString(indexFooter)
	_, err := io.WriteString(w, b.String())
	return err
}

const indexPreamble = "Every recipe here has passed the round-trip harness: its checks fail against an\n" +
	"empty stack, and pass after its data has been seeded, backed up, restored, and\n" +
	"checked by the same `restored check` a user runs.\n\n" +
	"    restored check --recipe <name> --source restic --from /srv/backups/restic\n\n" +
	"Each directory has a README saying which of your directories each input is.\n\n"

const indexFooter = "Yours is not here? [`recipes/TEMPLATE`](TEMPLATE/) is the skeleton, and\n" +
	"[CONTRIBUTING.md](../CONTRIBUTING.md#add-a-recipe-in-10-minutes) is the ten-minute\n" +
	"walk-through. If you already have a compose file for the application, start with\n\n" +
	"    restored recipe init myapp --compose ~/docker/myapp/docker-compose.yml\n\n" +
	"which turns it into a draft that already validates.\n"

// Markers around the recipe table in README.md. The same shape scripts/capture-demo.sh
// uses for the demo output, and for the same reason: a table of what ships is a claim,
// and a claim in a README goes stale the moment nobody is watching it.
const (
	readmeBegin = "<!-- BEGIN recipes-table -->"
	readmeEnd   = "<!-- END recipes-table -->"
)

// spliceReadmeTable rewrites the recipe table in README.md in place. This is the one
// target that edits a file rather than writing to stdout, because the table lives in
// the middle of a document a human wrote.
func spliceReadmeTable(path string) error {
	raw, err := os.ReadFile(path)
	if err != nil {
		return err
	}
	text := string(raw)
	start := strings.Index(text, readmeBegin)
	end := strings.Index(text, readmeEnd)
	if start < 0 || end < 0 || end < start {
		return fmt.Errorf("%s: the %s / %s markers are missing", path, readmeBegin, readmeEnd)
	}

	b := &strings.Builder{}
	b.WriteString(readmeBegin + "\n\n")
	b.WriteString("| recipe | application | state it restores | checks |\n|---|---|---|---|\n")
	for _, name := range recipe.BundledNames() {
		r, err := recipe.LoadBundled(name)
		if err != nil {
			return err
		}
		fmt.Fprintf(b, "| [`%s`](recipes/%s/) | %s | %s | %d |\n",
			name, name, r.Metadata.Title, inputSummary(r), len(r.Checks))
	}
	b.WriteString("\n")

	out := text[:start] + b.String() + text[end:]
	if out == text {
		return nil
	}
	return os.WriteFile(path, []byte(out), 0o644)
}

// inputSummary describes what a recipe restores, in the words a person searching for
// their own application would use.
func inputSummary(r *recipe.Recipe) string {
	var parts []string
	seen := map[string]bool{}
	for _, name := range r.InputOrder {
		in := r.Inputs[name]
		var label string
		switch in.Kind {
		case "dir":
			label = "directories"
		case "sqlite":
			label = "SQLite"
		case "postgres-dump":
			label = "PostgreSQL"
		default:
			label = in.Kind
		}
		if !seen[label] {
			seen[label] = true
			parts = append(parts, label)
		}
	}
	return strings.Join(parts, " + ")
}

// ---- helpers ---------------------------------------------------------------

func set(keys []string) map[string]bool {
	out := make(map[string]bool, len(keys))
	for _, k := range keys {
		out[k] = true
	}
	return out
}

func codeList(keys []string) string {
	out := make([]string, len(keys))
	for i, k := range keys {
		out[i] = "`" + k + "`"
	}
	return strings.Join(out, ", ")
}

func sortedKeys[V any](m map[string]V) []string {
	out := make([]string, 0, len(m))
	for k := range m {
		out = append(out, k)
	}
	sort.Strings(out)
	return out
}
